HEADER = """\
// GENERATED by scripts/build-icons.py from @iconify-json/solar. Do not edit; add icons there.
// Icons: Solar by 480 Design, CC BY 4.0 (https://github.com/480-Design/Solar-Icon-Set).
// Linear is the default; `bold` renders the Bold variant of the same glyph for active/selected state.
// Size with `size-*` classes (default 1em); colour follows currentColor. Decorative unless given aria-label.
import type { SVGProps } from "react";

export type IconProps = SVGProps<SVGSVGElement> & { bold?: boolean };
export type IconComponent = (props: IconProps) => React.JSX.Element;

function Solar({ linear, boldBody, bold, ...props }: IconProps & { linear: string; boldBody: string }) {
  const labelled = props["aria-label"] !== undefined;
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width="1em"
      height="1em"
      viewBox="0 0 24 24"
      aria-hidden={labelled ? undefined : true}
      role={labelled ? "img" : undefined}
      {...props}
      dangerouslySetInnerHTML={{ __html: bold ? boldBody : linear }}
    />
  );
}
"""


def body(name):
    icon = SOLAR["icons"].get(name)
    if icon is None:
        parent = SOLAR.get("aliases", {}).get(name, {}).get("parent")
        icon = SOLAR["icons"].get(parent) if parent else None
    assert icon is not None, f"Solar has no {name}"
    assert icon.get("width", SOLAR.get("width", 24)) == 24 and icon.get("height", SOLAR.get("height", 24)) == 24, name
    return icon["body"]


def main():
    lines = [HEADER]
    for app, solar in ICONS.items():
        lines.append(f"export const {app}: IconComponent = (props) => (\n  <Solar {{...props}} linear={{{json.dumps(body(solar + '-linear'))}}} boldBody={{{json.dumps(body(solar + '-bold'))}}} />\n);")
    (UI / "src/components/icons.tsx").write_text("\n".join(lines) + "\n")
    print(f"wrote {len(ICONS)} icons")


main()
