export function hookRegistryJson(hooks: ReadonlyArray<Hook>): string {
  return `${JSON.stringify({ version: 1, hooks }, null, 2)}\n`;
}

/**
 * The hook runner. It reads `hooks.json` next to itself, applies the hook's
 * canonical matcher to the harness payload, and runs the hook in the
 * harness's working directory with `CANONFIG_ROOT` set to the folder.
 */
export function hookRunnerSource(registryFile: string): string {
  return `#!/usr/bin/env node
// Generated by Canonfig. Edit hooks in ~/.canonfig/canonfig.jsonc instead.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const runtimeDir = path.dirname(fileURLToPath(import.meta.url));
const folder = path.dirname(runtimeDir);
let registry;
try { registry = JSON.parse(fs.readFileSync(path.join(runtimeDir, ${JSON.stringify(registryFile)}), "utf8")); }
catch { process.exit(0); }
const hooks = Array.isArray(registry?.hooks) ? registry.hooks : [];
const args = process.argv.slice(2);
const arg = (name) => { const index = args.indexOf(name); return index >= 0 ? args[index + 1] : undefined; };
const hookId = arg("--hook");
const target = arg("--target") || "unknown";
const event = arg("--event") || "unknown";
const hook = hooks.find((candidate) => candidate.id === hookId);
if (!hook) process.exit(0);

let rawText = "";
try { rawText = fs.readFileSync(0, "utf8"); } catch { rawText = ""; }
let raw;
try { raw = rawText.trim() ? JSON.parse(rawText) : {}; } catch { raw = { raw: rawText }; }
const toolName = String(raw.tool_name ?? raw.toolName ?? raw.tool ?? raw.name ?? raw.input?.tool ?? raw.input?.toolName ?? "");
const toolInput = raw.tool_input ?? raw.toolInput ?? raw.input ?? raw.args ?? {};
const serialized = JSON.stringify({ toolName, toolInput, raw });

const capabilityPatterns = {
  shell: /(bash|shell|terminal|execute|exec|command|run_command)/i,
  read: /(read|view|cat|glob|grep|search|list|find)/i,
  write: /(write|edit|patch|create|delete|move|replace)/i,
  search: /(grep|glob|search|find|list)/i,
  web: /(web|fetch|browser|http)/i,
  mcp: /(mcp|server)/i,
  subagent: /(task|agent|subagent)/i,
  test: /(test|spec|check|verify)/i,
  git: /(git|commit|branch|diff|push|pull)/i,
};
const matchesTool = !hook.matcher?.tools?.length || hook.matcher.tools.some((name) => {
  if (name === toolName) return true;
  try { return new RegExp(name).test(toolName); } catch { return false; }
});
const matchesCapability = !hook.matcher?.capabilities?.length || hook.matcher.capabilities.some((capability) => capabilityPatterns[capability]?.test(toolName));
let matchesInput = true;
if (hook.matcher?.inputRegex) {
  try { matchesInput = new RegExp(hook.matcher.inputRegex).test(serialized); }
  catch (error) { console.error(\`Invalid inputRegex for hook \${hook.id}: \${error.message}\`); process.exit(2); }
}
if (!matchesTool || !matchesCapability || !matchesInput) process.exit(0);

const normalized = {
  version: 1,
  hookId: hook.id,
  target,
  event,
  cwd: process.cwd(),
  toolName,
  toolInput,
  raw,
};
const [command, ...commandArgs] = hook.run;
const result = spawnSync(command, commandArgs, {
  cwd: process.cwd(),
  env: {
    ...process.env,
    CANONFIG_ROOT: folder,
    CANONFIG_HOOK_ID: hook.id,
    CANONFIG_TARGET: target,
    CANONFIG_EVENT: event,
    CANONFIG_TOOL_NAME: toolName,
  },
  input: JSON.stringify(normalized),
  encoding: "utf8",
  timeout: hook.timeoutMs,
  maxBuffer: 16 * 1024 * 1024,
});

let output;
try { output = result.stdout?.trim() ? JSON.parse(result.stdout) : undefined; } catch { output = undefined; }
const reason = String(output?.reason ?? result.stderr?.trim() ?? result.error?.message ?? \`Canonfig hook \${hook.id} failed\`);
const denied = result.status === 2 || output?.decision === "deny" || output?.permission === "deny" || output?.block === true;
const failed = result.error || result.status === null || (result.status !== 0 && result.status !== 2);
if (denied || (failed && hook.onFailure === "block")) {
  console.error(reason);
  process.exit(2);
}
if (failed && hook.onFailure === "warn") console.error(reason);
if (output?.message) console.log(String(output.message));
else if (result.stdout && !output) process.stdout.write(result.stdout);
process.exit(0);
`;
}

/**
 * Shared plugin prelude, after the plugin's own `imports`. `runCanonfig` runs
 * the hook runner at its absolute path with the system `node`, because some
 * clients embed a different runtime in `process.execPath`.
 */
function pluginPreamble(target: string, runner: string, imports: ReadonlyArray<string>): string {
  return `// Generated by Canonfig. Edit hooks in ~/.canonfig/canonfig.jsonc instead.
import { execFile } from "node:child_process";${imports.map((line) => `\n${line}`).join("")}

const runner = ${JSON.stringify(runner)};
function runCanonfig(hookId, event, payload, timeoutMs) {
  return new Promise((resolve) => {
    const child = execFile(
      "node",
      [runner, "--hook", hookId, "--target", ${JSON.stringify(target)}, "--event", event],
      {
        cwd: process.cwd(),
        encoding: "utf8",
        timeout: Math.max(1, timeoutMs + 1000),
        maxBuffer: 16 * 1024 * 1024,
      },
      (error, stdout, stderr) => {
        const reason = String(stderr || stdout || error?.message || "Blocked by Canonfig hook").trim();
        resolve({ blocked: error !== null, reason });
      },
    );
    child.stdin?.on("error", () => {});
    child.stdin?.end(JSON.stringify(payload ?? {}));
  });
}
`;
}

function runCall(hook: Hook): string {
  return `const result = await runCanonfig(${JSON.stringify(hook.id)}, ${JSON.stringify(hook.event)}, payload, ${hook.timeoutMs});`;
}

/** A subagent for the Amp plugin with its native tool names. */
export interface AmpAgent {
  readonly agent: AgentDocument;
  readonly tools: ReadonlyArray<string>;
}

function ampAgentRegistration({ agent, tools }: AmpAgent): Array<string> {
  // Escape underscores as well as hyphens so distinct canonical IDs stay distinct.
  const identifier = agent.id.replaceAll("_", "_u").replaceAll("-", "_h");
  const variable = `canonfigAgent_${identifier}`;
  const toolName = `canonfig_${identifier}_subagent`;
  const model = agent.model === "inherit" ? [] : [`    model: ${JSON.stringify(agent.model)},`];
  return [
    `  const ${variable} = amp.createAgent({`,
    `    name: ${JSON.stringify(agent.id)},`,
    ...model,
    `    instructions: ${JSON.stringify(agent.content.trim())},`,
    `    tools: ${JSON.stringify(tools.length > 0 ? tools : "all")},`,
    "  });",
    "  amp.registerTool({",
    `    name: ${JSON.stringify(toolName)},`,
    `    description: ${JSON.stringify(agent.description)},`,
    "    inputSchema: { type: \"object\", properties: { request: { type: \"string\" } }, required: [\"request\"] },",
    "    async execute(input, ctx) {",
    "      const request = typeof input.request === \"string\" ? input.request : \"\";",
    "      if (!request.trim()) return \"Missing subagent request.\";",
    `      const result = await ${variable}.run(request, { parentThreadID: ctx.thread.id, timeoutMs: 10 * 60 * 1000 });`,
    "      return result.text;",
    "    },",
    "  });",
  ];
}

/** A command palette entry that appends the command prompt to the thread. */
function ampCommandRegistration(command: CommandDocument): Array<string> {
  const argument = command.argumentHint
    ? [
      `      const input = await ctx.ui.input({ title: ${JSON.stringify(command.argumentHint)} });`,
      "      if (input === undefined || input === null) return;",
      "      const content = input.trim() ? `${prompt}\\n\\nArguments: ${input.trim()}` : prompt;",
    ]
    : ["      const content = prompt;"];
  return [
    "  {",
    `    const prompt = ${JSON.stringify(command.content.trim())};`,
    `    amp.registerCommand(${JSON.stringify(command.id)}, { title: ${JSON.stringify(command.id)}, description: ${JSON.stringify(command.description)} }, async (ctx) => {`,
    "      if (!ctx.thread) { await ctx.ui.notify(\"Open a thread first, then run this command again.\"); return; }",
    ...argument,
    "      await ctx.thread.append([{ type: \"user-message\", content }]);",
    "    });",
    "  }",
  ];
}

/** Amp plugin carrying hooks, subagents and commands. */
export function ampPluginSource(
  runner: string,
  hooks: ReadonlyArray<NativeHook>,
  agents: ReadonlyArray<AmpAgent>,
  commands: ReadonlyArray<CommandDocument>,
): string {
  const registrations = hooks.map(({ hook, event }) => {
    const rejection = event === "tool.call"
      ? "if (result.blocked) return { action: \"reject-and-continue\", message: result.reason };"
      : "if (result.blocked) throw new Error(result.reason);";
    return `  amp.on(${JSON.stringify(event)}, async (payload) => { ${runCall(hook)} ${rejection} });`;
  });
  const body = [
    ...registrations,
    ...agents.flatMap(ampAgentRegistration),
    ...commands.flatMap(ampCommandRegistration),
  ];
  return `${pluginPreamble("amp", runner, ['import type { PluginAPI } from "@ampcode/plugin";'])}\nexport default function canonfig(amp: PluginAPI) {\n${body.join("\n")}\n}\n`;
}

/** Pi or Oh My Pi extension carrying hooks. */
export function piPluginSource(target: "pi" | "oh-my-pi", runner: string, hooks: ReadonlyArray<NativeHook>): string {
  const registrations = hooks.map(({ hook, event }) => {
    const result = hook.event === "before_tool"
      ? "if (result.blocked) return { block: true, reason: result.reason };"
      : "if (result.blocked) throw new Error(result.reason);";
    return `  pi.on(${JSON.stringify(event)}, async (payload) => { ${runCall(hook)} ${result} });`;
  }).join("\n");
  const packageName = target === "pi" ? "@earendil-works/pi-coding-agent" : "@oh-my-pi/pi-coding-agent";
  return `${pluginPreamble(target, runner, [`import type { ExtensionAPI } from ${JSON.stringify(packageName)};`])}\nexport default function canonfig(pi: ExtensionAPI) {\n${registrations}\n}\n`;
}

/** OpenCode or Kilo plugin carrying tool hooks. */
export function openCodePluginSource(target: "opencode" | "kilo", runner: string, hooks: ReadonlyArray<NativeHook>): string {
  const handler = (nativeEvent: string): string => hooks
    .filter(({ event }) => event === nativeEvent)
    .map(({ hook }) => `      { const payload = { ...input, ...output }; ${runCall(hook)} if (result.blocked) throw new Error(result.reason); }`)
    .join("\n");
  return `${pluginPreamble(target, runner, [])}\nexport const CanonfigPlugin = async () => ({\n  "tool.execute.before": async (input, output) => {\n${handler("tool.execute.before")}\n  },\n  "tool.execute.after": async (input, output) => {\n${handler("tool.execute.after")}\n  },\n});\n`;
}
