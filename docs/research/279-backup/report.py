#!/usr/bin/env python3
"""Render the committed aggregate measurements without accessing private inputs."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PRIMARY = ["primary-results.json", "primary-remaining-results.json", "primary-tmpfs-results.json"]
ALGORITHMS = ["gzip-9", "zstd-1", "zstd-6", "zstd-19", "zstd-22-long31", "xz-9e", "brotli-11", "bzip3-32", "lz4-9", "7z-ultra", "zpaq-max"]


def table(headers, rows):
    return ["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |", *["| " + " | ".join(map(str, row)) + " |" for row in rows], ""]


def metrics(row):
    if row["status"] != "ok":
        return [row["status"], "n/a", "n/a", "n/a", "n/a", "n/a"]
    assert row["round_trip"] is True
    return [str(row["compressed_bytes"]), f'{row["ratio"]:.4f}', f'{row["compression"]["seconds"]:.3f}',
            f'{row["decompression"]["seconds"]:.3f}', f'{row["compression"]["peak_rss_kib"] / 1024:.1f}',
            f'{row["decompression"]["peak_rss_kib"] / 1024:.1f}']


def render():
    reports = [(name, json.loads((ROOT / name).read_text())) for name in PRIMARY]
    selected = {}
    failures = []
    for name, report in reports:
        for row in report["rows"]:
            key = (row["corpus"], row["algorithm"])
            if key not in selected or row["status"] == "ok":
                selected[key] = row
            if row["status"] != "ok":
                failures.append([name, *key, row["status"], row["compression"]["exit_code"]])
    lines = ["# Compression measurements", "", "Generated by `python3 docs/research/279-backup/report.py`. Raw JSON remains authoritative.", "",
             "Ratio is compressed bytes divided by tar bytes. Times are wall seconds. RSS is compressor/decompressor peak MiB, not the Python feeder's memory. Each successful row passed a full-stream SHA-256 round trip.", "",
             "These are single runs on a shared ARM64 Linux host, not confidence intervals. Page-cache warmth and competing work affect time comparisons. Later successful continuation rows replace interrupted measurements; failures remain below.", ""]
    headers = ["Algorithm", "Compressed bytes / failure", "Ratio", "Compress s", "Restore s", "Compress MiB", "Restore MiB"]
    for corpus in ["folder", "folder-and-harness-configuration"]:
        rows = [selected[(corpus, algorithm)] for algorithm in ALGORITHMS]
        first = rows[0]
        lines += [f"## {corpus}", "", f'{first["sample_files"]:,} files; {first["sample_bytes"]:,} input bytes; {first["tar_bytes"]:,} tar bytes.', ""]
        lines += table(headers, [[row["algorithm"], *metrics(row)] for row in rows])
    lines += ["## Primary interruptions", ""]
    lines += table(["Raw file", "Corpus", "Algorithm", "Status", "Exit"], failures)
    heavy = json.loads((ROOT / "heavy-results.json").read_text())
    assert heavy["private_copies_removed"] is True, "Heavy measurements are not complete"
    lines += ["## Heavy tier", "", "A fixed-seed, proportional-byte sample reads live files without copying them. Changing files and timeouts are failures, not zero-byte results. No private names or content appear in these artifacts.", ""]
    for corpus in sorted({row["corpus"] for row in heavy["rows"]}):
        rows = [row for row in heavy["rows"] if row["corpus"] == corpus]
        first = rows[0]
        population = heavy["population"][corpus]
        lines += [f"### {corpus}", "", f'{first["sample_files"]:,} sampled files; {first["sample_bytes"]:,} sampled bytes from {population["bytes"]:,} category bytes.', ""]
        lines += table(headers, [[row["algorithm"], *metrics(row)] for row in rows])
    lines += ["## Extrapolations, not full-folder measurements", "", "Each estimate scales a successful sample by category bytes / sampled bytes. Prefix sampling, file-size distribution and cross-file redundancy can bias it. Missing categories prevent a defensible whole-folder total.", ""]
    estimates = []
    for row in heavy["rows"]:
        estimate = row.get("extrapolated_full_category")
        if estimate:
            estimates.append([row["corpus"], row["algorithm"], estimate["compressed_bytes"], estimate["compression_seconds"], estimate["decompression_seconds"]])
    lines += table(["Category", "Algorithm", "Estimated compressed bytes", "Estimated compress s", "Estimated restore s"], estimates)
    return "\n".join(lines)


if __name__ == "__main__":
    output = ROOT / "measurements.md"
    output.write_text(render())
    print(f"Wrote {output.name}")
